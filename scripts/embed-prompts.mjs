/**
 * Embed system prompt markdown into a TypeScript module so
 * `bun build --compile` single-file binaries (Homebrew/Scoop) include them.
 *
 * Bun's virtual FS (`/$bunfs/root/`) only contains files the bundler sees.
 * Runtime `readFileSync` of sibling `.md` files fails there with ENOENT.
 * Generated output: src/prompts/embedded.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = join(root, "src", "prompts");
const files = ["system.ask.md", "system.agent.md"];

const entries = files.map((name) => {
  const body = readFileSync(join(promptsDir, name), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
});

const out = `/* AUTO-GENERATED by scripts/embed-prompts.mjs — do not edit by hand.
 * Source of truth: system.ask.md / system.agent.md
 * Re-run: node scripts/embed-prompts.mjs
 */
export const EMBEDDED_PROMPTS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;

const candidate = readFileSync(join(promptsDir, "candidate-density-sections.md"), "utf8");
const outputs = [
  { path: join(promptsDir, "embedded.ts"), content: out },
  { path: join(promptsDir, "candidate-density-embedded.ts"), content: `export const DENSITY_SECTIONS = ${JSON.stringify(candidate)};\n` },
];
const check = process.argv.includes("--check");
for (const output of outputs) {
  if (check) {
    let current = "";
    try { current = readFileSync(output.path, "utf8"); } catch {}
    if (current !== output.content) {
      console.error(`Missing or stale ${output.path}; run: node scripts/embed-prompts.mjs`);
      process.exit(1);
    }
  } else {
    mkdirSync(promptsDir, { recursive: true });
    writeFileSync(output.path, output.content, "utf8");
  }
}
console.log(`Embedded prompts ${check ? "match" : "generated from"} their sources (${files.length} legacy prompts, 1 isolated candidate artifact)`);
