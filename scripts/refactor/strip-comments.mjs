/**
 * Removes comments from TypeScript sources using the TypeScript compiler's own
 * scanner, then proves that nothing but comments changed.
 *
 * Why not a regex: `//` and "slash star" appear inside string literals, template
 * literals, regular expressions and JSX text throughout this repository — agent
 * prompts contain URLs, shell pipelines and example code. Only a real scanner can
 * tell a comment from those, so every candidate range here comes from
 * `ts.createSourceFile` trivia, never from a pattern match on raw text.
 *
 * Safety model:
 *   1. Comment ranges are collected as leading trivia of real tokens.
 *   2. Ranges that change behavior are kept (see KEEP_PATTERNS): shebangs,
 *      licence and generated-file markers, and compiler/linter/coverage
 *      directives. Deleting those would change how the file is processed, which
 *      is not "removing a comment".
 *   3. After rewriting, the token stream of the new text is compared with the
 *      token stream of the original, ignoring trivia. A single differing token
 *      aborts the whole run and leaves every file untouched.
 *
 *   node scripts/refactor/strip-comments.mjs --check     # report only
 *   node scripts/refactor/strip-comments.mjs --write     # apply
 *   node scripts/refactor/strip-comments.mjs --write --path src/tools
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? undefined : args[index + 1];
};
const write = args.includes("--write");
const root = flag("path") ?? "src";
const verbose = args.includes("--verbose");

/** Comments whose text changes tooling behavior, so they are not comments to drop. */
const KEEP_PATTERNS = [
  /^#!/,
  /@license\b/i,
  /@preserve\b/i,
  /\bcopyright\b/i,
  /\bSPDX-/,
  /@ts-(expect-error|ignore|nocheck|check)\b/,
  /\beslint\b/,
  /\bprettier-ignore\b/,
  /\bbiome-ignore\b/,
  /\b(?:c8|istanbul|v8)\s+ignore\b/,
  /@vitest-environment\b/,
  /\bstryker\s+(?:disable|restore)\b/,
  /@jsx\b/,
  /@type\b/,
  /\bwebpackChunkName\b/,
  /\bGENERATED\b|\bgenerated by\b|\bdo not edit\b/i,
  /\bsourceMappingURL\b/,
];

/**
 * Generated outputs are never edited by hand: their content is reproduced by a
 * generator and verified by `embed-prompts:check` / `sync-version`.
 */
const GENERATED_FILES = new Set([
  "src/prompts/embedded.ts",
  "src/version.generated.ts",
]);

const scriptKind = (file) =>
  file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;

const parse = (file, text) =>
  ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, scriptKind(file));

/**
 * Token stream without trivia. Used as the equivalence proof: two files with the
 * same token kinds and texts differ only in comments and whitespace.
 */
const tokens = (file, text) => {
  // Leaf tokens from the real parser rather than a standalone scanner: only the
  // parser resolves template-literal spans, JSX text and regex-versus-division
  // correctly, and a verifier that is less accurate than the edit is worthless.
  const source = parse(file, text);
  const out = [];
  const visit = (node) => {
    // JSDoc is attached to the tree as nodes rather than trivia, so a token walk
    // would compare documentation with itself and report every removal as a
    // change. Comments are exactly what this tool is allowed to alter.
    if (
      node.kind >= ts.SyntaxKind.FirstJSDocNode &&
      node.kind <= ts.SyntaxKind.LastJSDocNode
    ) {
      return;
    }
    const children = node.getChildren(source);
    if (children.length === 0) {
      if (node.kind === ts.SyntaxKind.EndOfFileToken) return;
      out.push(`${node.kind}\u0000${node.getText(source)}`);
      return;
    }
    for (const child of children) visit(child);
  };
  for (const child of source.getChildren()) visit(child);
  return out;
};

/** Every comment range in the file, gathered from token trivia. */
const commentRanges = (source, text) => {
  const ranges = new Map();
  const add = (range) => {
    if (!range) return;
    ranges.set(`${range.pos}:${range.end}`, range);
  };
  const visit = (node) => {
    for (const range of ts.getLeadingCommentRanges(text, node.getFullStart()) ?? []) {
      add(range);
    }
    for (const range of ts.getTrailingCommentRanges(text, node.getEnd()) ?? []) {
      add(range);
    }
    for (const child of node.getChildren(source)) visit(child);
  };
  for (const child of source.getChildren()) visit(child);
  for (const range of ts.getLeadingCommentRanges(text, 0) ?? []) add(range);
  return [...ranges.values()].sort((left, right) => left.pos - right.pos);
};

const files = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      walk(full);
      continue;
    }
    if (!/\.tsx?$/.test(full)) continue;
    if (GENERATED_FILES.has(full.split("\\").join("/"))) continue;
    files.push(full);
  }
};
if (statSync(root).isDirectory()) walk(root);
else files.push(root);

const results = [];
let failures = 0;
let removedTotal = 0;
let keptTotal = 0;

for (const file of files) {
  const original = readFileSync(file, "utf8");
  const source = parse(file, original);
  const ranges = commentRanges(source, original);
  const dropped = [];
  for (const range of ranges) {
    const body = original.slice(range.pos, range.end);
    if (KEEP_PATTERNS.some((pattern) => pattern.test(body))) {
      keptTotal += 1;
      continue;
    }
    dropped.push(range);
  }
  if (dropped.length === 0) continue;

  // Cut from the end so earlier offsets stay valid. A comment that owns its whole
  // line takes the line with it; a trailing comment leaves the code line intact.
  let updated = original;
  for (const range of [...dropped].reverse()) {
    let start = range.pos;
    let end = range.end;
    let lineStart = start;
    while (lineStart > 0 && updated[lineStart - 1] !== "\n") lineStart -= 1;
    const beforeOnLine = updated.slice(lineStart, start);
    const isOwnLine = beforeOnLine.trim().length === 0;
    let afterEnd = end;
    while (afterEnd < updated.length && (updated[afterEnd] === " " || updated[afterEnd] === "\t")) {
      afterEnd += 1;
    }
    const endsLine = updated[afterEnd] === "\n" || afterEnd >= updated.length;
    if (isOwnLine && endsLine) {
      start = lineStart;
      end = afterEnd < updated.length ? afterEnd + 1 : afterEnd;
    } else if (endsLine) {
      start = start - beforeOnLine.length + beforeOnLine.trimEnd().length;
      end = afterEnd;
    } else {
      end = afterEnd;
    }
    // An inline comment can be the only separator between two tokens
    // (`a/*x*/b`), so removal keeps one space when both sides would otherwise
    // fuse into a single identifier or numeric literal.
    const previous = updated[start - 1] ?? "";
    const next = updated[end] ?? "";
    const glue =
      /[\w$]/.test(previous) && /[\w$]/.test(next) ? " " : "";
    updated = updated.slice(0, start) + glue + updated.slice(end);
  }

  const before = tokens(file, original);
  const after = tokens(file, updated);
  const sameTokens =
    before.length === after.length &&
    before.every((token, index) => token === after[index]);
  if (!sameTokens) {
    failures += 1;
    const at = before.findIndex((token, index) => token !== after[index]);
    console.error(
      `TOKEN MISMATCH ${file}: first difference at token ${at}: ` +
        `${JSON.stringify(before[at])} -> ${JSON.stringify(after[at])}`,
    );
    continue;
  }
  const diagnostics = parse(file, updated).parseDiagnostics ?? [];
  if (diagnostics.length > 0) {
    failures += 1;
    console.error(`PARSE ERROR after stripping ${file}: ${diagnostics.length} diagnostic(s)`);
    continue;
  }

  removedTotal += dropped.length;
  results.push({ file, dropped: dropped.length, updated, original });
  if (verbose) {
    console.log(`${file}: -${dropped.length} comment(s)`);
  }
}

if (failures > 0) {
  console.error(
    `strip-comments: ${failures} file(s) failed equivalence checks; nothing written`,
  );
  process.exit(1);
}

if (write) {
  for (const result of results) writeFileSync(result.file, result.updated);
}

const lineDelta = results.reduce(
  (total, result) =>
    total + result.original.split("\n").length - result.updated.split("\n").length,
  0,
);
console.log(
  `strip-comments: ${write ? "removed" : "would remove"} ${removedTotal} comment(s) ` +
    `from ${results.length} of ${files.length} file(s) under ${root}; ` +
    `kept ${keptTotal} behavior-bearing comment(s); ${lineDelta} fewer lines; ` +
    `token streams identical in every file`,
);
